/** 方案的“预计效果”不属于未来时段查询。历史与未来解析共用此入口。 */
export function needsFutureForecast(message: string): boolean {
  return /预测|预警|未来|将来|预防|明天|后天|今晚|明早|下周|下个月|下星期|下一(?:小时|分钟|天|周)|(?:\d+(?:\.\d+)?|[一二三四五六七八九十百半两]+)\s*(?:秒|分钟|小时|天|周|个月)\s*(?:之)?后|接下来(?:的)?\s*(?:\d+|[一二三四五六七八九十百半两]+)\s*(?:秒|分钟|小时|天|周)|接下来.*(?:网络|负载|拥塞|信号|覆盖|吞吐|时延|风险|趋势|会)/.test(message);
}
